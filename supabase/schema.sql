-- 1. Tabla de reseñas de usuarios (comentarios nuevos)
-- Nota: Las reseñas prehechas/deterministas de "Gemelos de Piel" viven en el
-- frontend (src/services/skinTwins.ts) y no necesitan migrarse.
create table if not exists public.reviews (
  id text primary key,
  perfume_id integer not null,
  user_id text null,
  author text not null default 'Usuario',
  skin_type text not null default 'General',
  hydration text not null default 'Media',
  climate text not null default 'Templado',
  rating numeric(2, 1) not null check (rating >= 1 and rating <= 5),
  duration text not null default '6-8 horas',
  sillage text null default 'Moderada',
  occasion text null default 'Uso diario',
  target text not null default 'both' check (target in ('global', 'twins', 'both')),
  comment text not null,
  created_at timestamptz not null default now()
);

create index if not exists idx_reviews_perfume_created
  on public.reviews (perfume_id, created_at desc);

-- 2. Tabla de usuarios de la app (registro e inicio de sesión)
create table if not exists public.app_users (
  id bigint generated by default as identity primary key,
  username text not null unique,
  password_hash text not null,
  created_at timestamptz not null default now()
);

-- 3. Tabla de perfiles de piel (Gemelos de Piel)
create table if not exists public.skin_profiles (
  id bigint generated by default as identity primary key,
  user_id text not null unique,
  skin_type text not null,
  hydration text not null,
  climate text not null,
  humidity text null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- 4. Row Level Security (RLS)
alter table public.reviews enable row level security;
alter table public.app_users enable row level security;
alter table public.skin_profiles enable row level security;

-- Lectura pública de reseñas
drop policy if exists "Reviews are publicly readable" on public.reviews;
create policy "Reviews are publicly readable"
  on public.reviews
  for select
  using (true);

-- Inserción abierta para reseñas (puedes restringir a auth.role() = 'authenticated' cuando uses Supabase Auth)
drop policy if exists "Anyone can insert reviews" on public.reviews;
create policy "Anyone can insert reviews"
  on public.reviews
  for insert
  with check (true);

-- Políticas para app_users (usado por el backend)
drop policy if exists "Backend can read app_users" on public.app_users;
create policy "Backend can read app_users"
  on public.app_users
  for select
  using (true);

drop policy if exists "Backend can insert app_users" on public.app_users;
create policy "Backend can insert app_users"
  on public.app_users
  for insert
  with check (true);

-- Políticas para skin_profiles
drop policy if exists "Public can read skin_profiles" on public.skin_profiles;
create policy "Public can read skin_profiles"
  on public.skin_profiles
  for select
  using (true);

drop policy if exists "Public can insert skin_profiles" on public.skin_profiles;
create policy "Public can insert skin_profiles"
  on public.skin_profiles
  for insert
  with check (true);

drop policy if exists "Public can update skin_profiles" on public.skin_profiles;
create policy "Public can update skin_profiles"
  on public.skin_profiles
  for update
  using (true)
  with check (true);

-- 5. Permisos explícitos para los roles anon y authenticated (necesario si usas SUPABASE_ANON_KEY)
grant usage on schema public to anon, authenticated;
grant select, insert on public.reviews to anon, authenticated;
grant select, insert on public.app_users to anon, authenticated;
grant select, insert, update on public.skin_profiles to anon, authenticated;
grant usage, select on all sequences in schema public to anon, authenticated;
